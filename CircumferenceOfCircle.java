public class CircumferenceOfCircle 
{
    public static void main(String[] args) 
    {

        float RadiusOfCircle = 5;
        float AreaOfCircle = 7;

        double CircumferenceOfCircle = 2  * 3.14f * RadiusOfCircle;
        double Area_Circle = 3.14f * AreaOfCircle * AreaOfCircle;

        System.out.println("The Circumference of the Circle is : " + CircumferenceOfCircle);
        System.out.println("The Area of the Circle is : " + Area_Circle);


    }
}
