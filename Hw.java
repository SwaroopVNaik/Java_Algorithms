public class Hw {
    public static void main(String[] args) {
        
        // Write a program to print all data type Byte, Short, Int, long, float , double, char, boolean

        // printing Byte
        byte Vals = (byte) 30;
        System.out.println("BYTE");
        System.out.println(Vals);

        System.out.println();

        // printing short 
        short vals_1 = 20;
        System.out.println("SHORT");
        System.out.println(vals_1);

        System.out.println();

        // printing integer 
        int age = 22; 
        System.out.println("INTEGER");
        System.out.println(age);

        System.out.println();

        // printing long
        long salary = 500000000; 
        System.out.println("LONG");
        System.out.println(salary);

        System.out.println();

        // Printing Float 
        float radiusOfCircle = 3.14f;
        System.out.println("FLOAT");
        System.out.println(radiusOfCircle);

        System.out.println();

        // Printing double
        double pi = 3.14234567890;
        System.out.println("DOUBLE");
        System.out.println(pi);

        System.out.println();

        // Printing char 
        char Alpha = 'S';
        System.out.println("CHAR");
        System.out.println(Alpha);

        System.out.println();

        // Printing BOOLEAN
        Boolean Value = false;
        System.out.println("BOOLEAN");
        System.out.println(Value);

        System.out.println();

    }
}
